#[cfg(test)]
mod tests {
    use proptest::prelude::*;
    use std::collections::{HashSet, VecDeque};

    // =====================================================
    // 01. Round trips: encode, then decode
    // =====================================================

    fn encode_hex(bytes: &[u8]) -> String {
        const DIGITS: &[u8; 16] = b"0123456789abcdef";
        let mut encoded = String::with_capacity(bytes.len() * 2);
        for &byte in bytes {
            encoded.push(char::from(DIGITS[usize::from(byte >> 4)]));
            encoded.push(char::from(DIGITS[usize::from(byte & 15)]));
        }
        encoded
    }

    fn decode_hex(text: &str) -> Result<Vec<u8>, &'static str> {
        if text.len() % 2 != 0 {
            return Err("hex length must be even");
        }
        let mut bytes = Vec::with_capacity(text.len() / 2);
        for pair in text.as_bytes().chunks_exact(2) {
            let high = char::from(pair[0]).to_digit(16).ok_or("invalid hex digit")?;
            let low = char::from(pair[1]).to_digit(16).ok_or("invalid hex digit")?;
            bytes.push(((high << 4) | low) as u8);
        }
        Ok(bytes)
    }
    // Byte chunks avoid slicing UTF-8 strings at potentially invalid boundaries.
    // The decoder accepts either case; the encoder emits lowercase only.
    // These tiny functions exist to illustrate tests, not optimize a hex codec.

    proptest! {
        #[test]
        fn codec_round_trip(bytes in proptest::collection::vec(any::<u8>(), 0..128)) {
            let encoded = encode_hex(&bytes);
            let decoded = decode_hex(&encoded);

            prop_assert_eq!(decoded, Ok(bytes));
        }
    }

    #[test]
    fn codec_known_examples() {
        assert_eq!(encode_hex(&[0, 15, 16, 255]), "000f10ff");
        assert_eq!(decode_hex("000F10FF"), Ok(vec![0, 15, 16, 255]));
        assert_eq!(decode_hex(""), Ok(vec![]));
        assert!(decode_hex("f").is_err());
        assert!(decode_hex("gg").is_err());
    }
    // Round trips can miss shared mistakes: an encoder and decoder could agree
    // on the WRONG alphabet. Known examples supply an external specification.
    // For arbitrary textual input, encode(decode(text)) may canonicalize case;
    // it need not reproduce the original spelling. Choose the right direction.

    // =====================================================
    // 02. Differential testing: compare with a simple reference
    // =====================================================

    fn unique_in_order(values: &[i16]) -> Vec<i16> {
        let mut seen = HashSet::new();
        values.iter().copied().filter(|value| seen.insert(*value)).collect()
    }

    fn unique_reference(values: &[i16]) -> Vec<i16> {
        let mut result = Vec::new();
        for &value in values {
            if !result.contains(&value) {
                result.push(value);
            }
        }
        result
    }

    proptest! {
        #[test]
        fn dedup_matches_reference(values in proptest::collection::vec(-10i16..=10, 0..80)) {
            prop_assert_eq!(unique_in_order(&values), unique_reference(&values));
        }
    }
    // The optimized version uses a set; the reference scans a vector. Their
    // different mechanisms make accidental shared implementation bugs less likely.
    // HashSet iteration order is irrelevant: output follows the original iterator.
    // A small value domain encourages duplicates. The contract preserves FIRST
    // occurrence order, unlike sorting and then calling dedup().
    // Reference testing is only as trustworthy as the reference and its contract.

    // =====================================================
    // 03. Invariants and idempotence: normalize whitespace
    // =====================================================

    fn normalize_whitespace(text: &str) -> String {
        text.split_whitespace().collect::<Vec<_>>().join(" ")
    }

    proptest! {
        #[test]
        fn normalization_preserves_tokens(text in "[a-z \\t\\n]{0,100}") {
            let normalized = normalize_whitespace(&text);
            prop_assert_eq!(normalize_whitespace(&normalized), normalized.clone());

            let before: Vec<_> = text.split_whitespace().collect();
            let after: Vec<_> = normalized.split_whitespace().collect();
            prop_assert_eq!(after, before);
            prop_assert!(!normalized.starts_with(' '));
            prop_assert!(!normalized.ends_with(' '));
            prop_assert!(!normalized.contains("  "));
        }
    }
    // Idempotence alone is weak: a function that always returns "" is idempotent!
    // Token preservation rules that out. This strategy covers a small ASCII domain;
    // it does not establish Unicode whitespace correctness for every input.
    // Use contract-specific Unicode examples or broader strategies when required.

    // =====================================================
    // 04. Operation sequences: compare a queue with a model
    // =====================================================

    #[derive(Clone, Debug)]
    enum Operation {
        Push(i16),
        Pop,
    }

    proptest! {
        #[test]
        fn queue_matches_model(operations in proptest::collection::vec(
            prop_oneof![Just(Operation::Pop), any::<i16>().prop_map(Operation::Push)],
            0..60
        )) {
            let mut queue = VecDeque::new();
            let mut model = Vec::new();

            for operation in operations {
                match operation {
                    Operation::Push(value) => {
                        queue.push_back(value);
                        model.push(value);
                    }
                    Operation::Pop => {
                        let expected = if model.is_empty() { None } else { Some(model.remove(0)) };
                        prop_assert_eq!(queue.pop_front(), expected);
                    }
                }
                prop_assert_eq!(queue.len(), model.len());
                prop_assert!(queue.iter().eq(model.iter()));
            }
        }
    }
    // One generated case is an ENTIRE operation sequence. State starts fresh for
    // each case; shrinking can simplify both the sequence and its payload values.
    // The slow Vec model makes FIFO behavior easy to inspect. Here VecDeque is
    // the teaching stand-in for your own queue/cache/buffer API.
    // This uses ordinary proptest, not the separate proptest-state-machine crate.
    // It tests sequential state transitions, not multithreaded interleavings.

    // =====================================================
    // 05. Regression tests: preserve a discovered counterexample
    // =====================================================

    fn add_two_fixed(value: i32) -> i32 {
        value + 2
    }

    #[test]
    fn regression_add_two_at_ten() {
        // File 01's buggy branch returned 11 for this input.
        assert_eq!(add_two_fixed(10), 12);
    }

    proptest! {
        #[test]
        fn fixed_addition_matches_contract(value in -1_000i32..=1_000) {
            prop_assert_eq!(add_two_fixed(value) - value, 2);
        }
    }
    // Discovery -> inspect counterexample -> understand bug -> fix implementation
    // -> add a focused ordinary test -> retain a broader property.
    // The regression's name records WHY that input matters. A concrete test also
    // stays stable when a later strategy change alters generated/replayed inputs.
    // The bounded domain here avoids overflowing i32; this isn't an all-i32 API.

    // =====================================================
    // 06. Configuration and ignored larger tests
    // =====================================================

    proptest! {
        #![proptest_config(ProptestConfig {
            cases: 128,
            max_shrink_iters: 2_048,
            .. ProptestConfig::default()
        })]

        #[test]
        fn configured_codec_length(bytes in proptest::collection::vec(any::<u8>(), 0..128)) {
            prop_assert_eq!(encode_hex(&bytes).len(), bytes.len() * 2);
        }
    }
    // This configuration applies to THIS proptest! block, not all tests.
    // cases is the successful generated-case budget, not the number of #[test]
    // functions or the total including shrinking, rejected inputs, and replay.
    // max_shrink_iters limits simplification effort after a failure; reaching
    // that limit doesn't turn a failing property into a passing one.
    // Config struct fields use Rust's field: value syntax (not attribute key=value).

    proptest! {
        #![proptest_config(ProptestConfig::with_cases(1_024))]

        #[test]
        #[ignore="larger optional run; request explicitly"]
        fn larger_codec_run(bytes in proptest::collection::vec(any::<u8>(), 0..512)) {
            prop_assert_eq!(decode_hex(&encode_hex(&bytes)), Ok(bytes));
        }
    }
    // cargo test --bin 03_practical_properties larger_codec_run -- --ignored
    // Unlike file 01's ignored demo, this test is expected to PASS.
    // Ordinary default-config blocks can use a shell environment override:
    // PROPTEST_CASES=1000 cargo test --bin 03_practical_properties codec_round_trip
    // Explicit cases/with_cases settings above take precedence over that default.
    // More cases cannot rescue a weak property or an inappropriate input domain.

    // =====================================================
    // 07. Failure persistence and reproducibility
    // =====================================================

    // Default std-enabled Proptest remembers discovered failures in files, usually
    // under proptest-regressions/. The test failure output identifies the path.
    // It stores reproduction seeds, not a Serde serialization of your input.
    // Future runs replay persisted seeds before trying fresh generated cases.
    // Commit those files so collaborators/CI can also replay known problem cases.
    //
    // Reproduce a failure with the same property, strategies, dependency versions,
    // and persisted data. Read the reported counterexample and add a concrete
    // regression too: changing a strategy can change what an old seed generates.
    // A seed can't stabilize unrelated randomness, clocks, or external services.
    // Don't edit persistence records by guessing seed syntax; let Proptest write
    // them. Keep Cargo.lock under version control as appropriate for your project.
    //
    // This guide contains no deliberate failure, so it need not create a new
    // regression file. Run file 01's ignored failure demo to see persistence.
    // failure_persistence: None in Config disables it for a block, but normally
    // keeping useful failure records is preferable. No custom runner is needed.

    // =====================================================
    // 08. Review: filtering, output, unit and integration tests
    // =====================================================

    #[test]
    fn codec_boundary_examples() -> Result<(), &'static str> {
        assert_eq!(decode_hex("00")?, vec![0]);
        assert_eq!(decode_hex("ff")?, vec![255]);
        assert!(decode_hex("0z").is_err());
        Ok(())
    }
    // Chapter 11 connections:
    // - This ordinary Result-returning test uses ? where decoding must succeed.
    // - Expected Err needs an assertion, not ?.
    // - cargo test --bin 03_practical_properties codec filters by test-name text.
    // - -- --show-output displays output from successful tests too.
    // - -- --ignored runs ignored tests; -- --include-ignored includes both kinds.
    //
    // The functions here live in cfg(test) only to make the tutorial standalone.
    // In an application, put real implementation code outside the test module;
    // unit tests can then use super::* and exercise private functions as needed.
    // Integration tests under tests/ use the public API of your src/lib.rs crate.
    // They don't need cfg(test), and proptest! works there too. A binary's private
    // functions aren't automatically importable by an integration test crate.
    //
    // Choose properties from your specification, not merely by copying the code
    // under test. Combine known examples, generated inputs, and regression tests.
}
