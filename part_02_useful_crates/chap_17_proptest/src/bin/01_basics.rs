//! Proptest basics, connected to Rust Book Chapter 11.
//!
//! Setup inside chap_17_proptest:
//!     cargo add proptest@1 --dev
//!
//! Save as src/bin/01_basics.rs.
//!     cargo run --bin 01_basics      # Print the learning outline, not run tests.
//!     cargo test --bin 01_basics     # Run ordinary + property tests.
//!
//! A PROPERTY is a rule expected to hold throughout a chosen input domain.
//! A STRATEGY describes how to generate inputs and simplify failing ones.
//! SHRINKING searches for a simpler input that still makes the test fail.
//! Passing sampled cases is useful evidence, not a mathematical proof.
//!
//! Proptest supplements #[test], assertions, and Cargo's existing test runner.
//! It doesn't replace specific boundary examples or regression tests.
//! Keep production behavior deterministic for a given input whenever possible.
//!
//! References:
//! https://proptest-rs.github.io/proptest/proptest/getting-started.html
//! https://docs.rs/proptest/latest/proptest/macro.proptest.html

fn main() {
    println!();

    println!("01. Review: one ordinary test, one chosen input");
    println!("cargo test --bin 01_basics example_add_two");
    println!("\n============================\n");

    println!("02. First property: generated inputs and prop_assert_eq!");
    println!("cargo test --bin 01_basics addition_is_reversible");
    println!("\n============================\n");

    println!("03. any::<T>(): broad inputs and integer overflow");
    println!("cargo test --bin 01_basics checked_addition");
    println!("\n============================\n");

    println!("04. Vector property: reversing twice restores the input");
    println!("cargo test --bin 01_basics reverse_twice");
    println!("\n============================\n");

    println!("05. Sorting: check meaningful invariants");
    println!("cargo test --bin 01_basics sorting");
    println!("\n============================\n");

    println!("06. Review: Result errors versus expected panics");
    println!("cargo test --bin 01_basics score");
    println!("\n============================\n");

    println!("07. Shrinking: explicitly run an ignored failing property");
    println!();
    println!("cargo test --bin 01_basics shrinking_finds_boundary -- --ignored");
    println!("This last command intentionally FAILS so you can inspect the report.");
    // main is only an outline. cargo test uses a generated test-harness entry
    // point; it doesn't execute this main. Test order is not the outline order.
    // Use -- --show-output to display captured output from successful tests.
}

#[cfg(test)]
mod tests {
    use proptest::prelude::*;
    // cfg(test) excludes this module from a normal build/run. Because Proptest
    // is only imported here, it can remain a dev-dependency.
    // The prelude brings proptest!, assertion macros, any, and common traits
    // into scope. No TestRunner plumbing is needed for these introductory tests.

    // =====================================================
    // 01. Review: one ordinary test, one chosen input
    // =====================================================

    fn add_two(value: i32) -> i32 {
        value + 2
    }

    #[test]
    fn example_add_two() {
        let input = 35;
        let result = add_two(input);
        assert_eq!(result, 37, "adding two should produce 37 for input 35");
    }
    // Same setup -> act -> assert pattern as your Chapter 11 examples.
    // This checks one concrete input. The property below checks a relationship
    // across generated inputs; neither test replaces the other.

    // =====================================================
    // 02. First property: generated inputs and prop_assert_eq!
    // =====================================================

    proptest! {
        #[test]
        fn addition_is_reversible(value in -1_000i32..=1_000) {
            let result = add_two(value);
            prop_assert_eq!(result - 2, value,
                "subtracting two should recover the original input {}", value);
        }
    }
    // Read the unusual parameter as: 'value is generated by this strategy'.
    // -1_000i32..=1_000 is an inclusive range, NOT one iterator we manually loop.
    // proptest! creates a Cargo test that runs the body repeatedly with inputs.
    // The numeric bounds avoid overflow in this particular calculation.
    // prop_assert_eq! reports a property failure, allowing the runner to shrink.
    // Ordinary assert! also causes a failure through panic, but property assertion
    // macros are designed to return Proptest test failures with diagnostics.
    // Don't add -> io::Result<()> as you would to an ordinary Chapter 11 test:
    // let the macro manage the property body's test-result handling.

    // =====================================================
    // 03. any::<T>(): broad inputs and integer overflow
    // =====================================================

    proptest! {
        #[test]
        fn checked_addition(a in any::<u8>(), b in any::<u8>()) {
            let wide_sum = u16::from(a) + u16::from(b);
            let result = a.checked_add(b);

            if wide_sum <= u16::from(u8::MAX) {
                prop_assert_eq!(result, Some(wide_sum as u8));
            } else {
                prop_assert!(result.is_none(),
                    "{} + {} should overflow u8", a, b);
            }
        }
    }
    // any::<u8>() describes arbitrary u8 values, including boundary values.
    // It doesn't promise exhaustive enumeration or a uniform random distribution.
    // a + b directly as u8 could panic on overflow in debug tests. Decide what
    // arithmetic behavior you mean: checked, wrapping, saturating, or bounded.
    // Here a wider type supplies an independent, overflow-free reference result.
    // Don't 'fix' a failing property by excluding inputs the API must support.

    // =====================================================
    // 04. Vector property: reversing twice restores the input
    // =====================================================

    proptest! {
        #[test]
        fn reverse_twice(values in proptest::collection::vec(any::<i16>(), 0..40)) {
            let mut actual = values.clone();
            actual.reverse();
            actual.reverse();

            prop_assert_eq!(actual, values);
        }
    }
    // vec(element_strategy, length_range) generates Vec<i16>, here length 0..=39.
    // Empty vectors are valid cases. Length limits keep this tutorial inexpensive.
    // Inputs come from the strategy; the function body describes the property.
    // Strategies for collections and custom structures are expanded in file 02.
    // This standard-library example teaches a property shape you can reuse for
    // your own reversible transformations; it isn't a replacement for specifying
    // what ONE reversal should actually do.

    // =====================================================
    // 05. Sorting: check meaningful invariants
    // =====================================================

    proptest! {
        #[test]
        fn sorting_preserves_length_and_orders_values(
            values in proptest::collection::vec(-100i32..=100, 0..40)
        ) {
            let original_length = values.len();
            let mut sorted = values;
            sorted.sort();

            prop_assert_eq!(sorted.len(), original_length);
            prop_assert!(sorted.windows(2).all(|pair| pair[0] <= pair[1]),
                "output should be nondecreasing: {:?}", sorted);

            let mut sorted_again = sorted.clone();
            sorted_again.sort();
            prop_assert_eq!(sorted_again, sorted);
        }
    }
    // These check length preservation, order, and idempotence (sorting twice
    // gives the same result). windows(2) works even for empty/singleton vectors.
    // They are useful but INCOMPLETE: replacing every value with zero passes all
    // three! A complete sorting specification must also preserve the multiset
    // of values. Choosing strong properties matters more than test-case volume.
    // Practical reference comparisons and stronger properties follow in file 03.

    // =====================================================
    // 06. Review: Result errors versus expected panics
    // =====================================================

    fn validate_score(value: i32) -> Result<i32, &'static str> {
        if (1..=100).contains(&value) {
            Ok(value)
        } else {
            Err("score must be in 1..=100")
        }
    }

    proptest! {
        #[test]
        fn score_validation_matches_contract(value in -200i32..=200) {
            let result = validate_score(value);
            if (1..=100).contains(&value) {
                prop_assert_eq!(result, Ok(value));
            } else {
                prop_assert_eq!(result, Err("score must be in 1..=100"));
            }
        }
    }
    // Expected Err is data to ASSERT on, not something to propagate with ?.
    // As with ordinary Result-returning tests, ? is for operations that must
    // succeed. Expected failures need their own assertions.

    #[test]
    fn score_boundaries() -> Result<(), &'static str> {
        assert_eq!(validate_score(1)?, 1);
        assert_eq!(validate_score(100)?, 100);
        assert!(validate_score(0).is_err());
        assert!(validate_score(101).is_err());
        Ok(())
    }
    // Keep explicit boundary tests: generated sampling doesn't promise that
    // every boundary appears on every run. This reviews Chapter 11's Result + ?.

    #[test]
    #[should_panic(expected="score must be in 1..=100")]
    fn score_panicking_adapter_rejects_invalid_input() {
        validate_score(101).expect("score must be in 1..=100");
    }
    // This ordinary test reviews #[should_panic(expected="substring")].
    // validate_score itself returns Err; expect is the adapter that panics.
    // Don't annotate a whole generated property with should_panic just to test
    // invalid inputs: an unrelated assertion panic could satisfy that expectation.
    // Unexpected panics in an ordinary property are failures to investigate.

    // =====================================================
    // 07. Shrinking: explicitly run an ignored failing property
    // =====================================================

    fn add_two_buggy(value: i32) -> i32 {
        if value >= 10 { value + 1 } else { value + 2 }
    }

    #[test]
    fn buggy_function_happens_to_pass_one_example() {
        assert_eq!(add_two_buggy(3), 5);
    }

    proptest! {
        #[test]
        #[ignore="intentionally fails; run explicitly to see shrinking"]
        fn shrinking_finds_boundary(value in 10i32..1_000) {
            prop_assert_eq!(add_two_buggy(value), value + 2);
        }
    }
    // Run just this failure demo:
    // cargo test --bin 01_basics shrinking_finds_boundary -- --ignored
    //
    // All values in this chosen range expose the bug. After finding a failing
    // value, Proptest attempts simpler values that STILL fail; for this simple
    // range you should normally see a final counterexample of value = 10.
    // Read the 'minimal failing input' and assertion details, not just FAILED.
    // Shrinking generally finds a small counterexample, not a guaranteed global
    // minimum for every strategy/property; exact search traces can vary.
    //
    // This is a REAL failing test, not #[should_panic]. Normal cargo test skips
    // it because of ignore; --include-ignored intentionally includes it too.
    // The failing run may write a failure-persistence file for later replay.
    // We'll discuss persistence/configuration and permanent regression tests in
    // file 03. Fix the buggy implementation rather than weakening the property.
}
